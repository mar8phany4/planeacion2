#============================BALANCEO DE VIAJES GENERADOS Y ATRAIDOS======================================================================
st.subheader("Balanceo de viajes generados y atraídos", divider="yellow")
st.markdown("""
En este modelo el usuario puede escoger la cantidad de zonas. Hay dos formas de ingresar los datos
manualmente, o mediante un archivo CSV el cual debe estar organizado de las siguiente forma una columna tiene que contener el nombre de las zonas , otra de los viajes  generados por la zona y una de los viajes atraídos por la zona, 
si se tiene el nombre de un zona el valor de los viajes atraídos y generados por la zona debe de estar en la misma fila..
""")

st.markdown("**Propósito del balanceo:** que la suma de viajes atraídos sea igual a la suma de viajes generados.")

st.latex(r'''
    V_A = \sum_{n} V_{a_n}, \qquad V_G = \sum_{n} V_{g_n}, \qquad V_A = V_G
''')

st.markdown("""
donde Va_n =  cantidad de viajes atraídos por la zona n y Vg_n = cantidad de viajes generados por la zona n.
""")

st.markdown("**Procedimiento:** primero se calculan V_A y V_G con los valores originales.")

st.markdown("**Caso 1:** si V_A = V_G, las zonas ya están balanceadas.")

st.markdown("**Caso 2:** si V_A < V_G:")
st.latex(r'''
    d = \frac{V_G}{V_A}, \qquad V_{a_n}^{nuevo} = V_{a_n} \cdot d
''')

st.markdown("**Caso 3:** si V_G < V_A:")
st.latex(r'''
    d = \frac{V_A}{V_G}, \qquad V_{g_n}^{nuevo} = V_{g_n} \cdot d
''')

st.markdown("Con estos nuevos valores, ambas sumas resultan iguales.")
st.latex(r'''
    \sum_{n} V_{a_n}^{nuevo} = \sum_{n} V_{g_n}
    \quad \text{o} \quad
    \sum_{n} V_{a_n} = \sum_{n} V_{g_n}^{nuevo}
''')
n = st.number_input("Cantidad de zonas:", min_value=1, step=1, value=2)

st.subheader("Viajes Atraídos por Zona")
va = []
for i in range(n):
    valor = st.number_input(f"Viajes atraídos - Zona {i+1}:", min_value=0.0, step=0.1, key=f"va_{i}")
    va.append(valor)

st.subheader("Viajes Generados por Zona")
vg = []
for i in range(n):
    val = st.number_input(f"Viajes generados - Zona {i+1}:", min_value=0.0, step=0.1, key=f"vg_{i}")
    vg.append(val)

if st.button("Calcular"):
    total_viajes_atraidos = sum(va)
    total_viajes_generados = sum(vg)

    if total_viajes_atraidos < total_viajes_generados:
        f = total_viajes_generados / total_viajes_atraidos if total_viajes_atraidos != 0 else 1
        va_n = [x * f for x in va]
        vg_n = vg.copy()
        balanceado = "Viajes Atraídos (normalizados)"
        valores_balanceados = va_n

    elif total_viajes_generados < total_viajes_atraidos:
        f = total_viajes_atraidos / total_viajes_generados if total_viajes_generados != 0 else 1
        vg_n = [x * f for x in vg]
        va_n = va.copy()
        balanceado = "Viajes Generados (normalizados)"
        valores_balanceados = vg_n

    else:
        va_n = va.copy()
        vg_n = vg.copy()
        balanceado = "Ya están balanceados (sin cambios)"
        valores_balanceados = va_n
    st.write(f"**Suma de los viajes generados: {sum(vg):.2f}**")
    st.write(f"**Suma de los viajes atraidos: {sum(va):.2f}**")
    st.subheader(f"Valores balanceados: {balanceado}")
    for i in range(n):
        st.write(f"Zona {i+1}: {valores_balanceados[i]:.2f}")
    
st.write("balancear con un archivo csv")

